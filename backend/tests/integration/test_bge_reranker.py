"""The real reranker on questions in two languages; needs `make models`."""

import os
from pathlib import Path

import pytest

from assistant.adapters.bge_reranker import BgeReranker

pytestmark = pytest.mark.integration

MODELS_DIR = Path(
    os.environ.get("ASSISTANT_MODELS_DIR", Path(__file__).parents[3] / "data" / "models")
)


@pytest.fixture(scope="module")
def reranker() -> BgeReranker:
    BgeReranker.ensure_ready(MODELS_DIR)
    return BgeReranker(MODELS_DIR)


def test_a_polish_question_finds_the_english_answer(reranker: BgeReranker) -> None:
    scores = reranker.score(
        "Jak długo dostawcy przechowują rejestry zdarzeń?",
        [
            "Providers keep the logs automatically generated by their high-risk AI systems "
            "for a period of at least six months.",
            "Member States shall designate notifying authorities.",
        ],
    )

    assert scores[0] > scores[1]
