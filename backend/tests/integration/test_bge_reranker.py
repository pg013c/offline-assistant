"""The real reranker on questions in two languages; needs `make models`."""

import os
from pathlib import Path

import pytest

from assistant.adapters.bge_reranker import BgeReranker

pytestmark = pytest.mark.integration

MODELS_DIR = Path(
    os.environ.get("ASSISTANT_MODELS_DIR", Path(__file__).parents[3] / "data" / "models")
)


@pytest.fixture(scope="module")
def reranker() -> BgeReranker:
    BgeReranker.ensure_ready(MODELS_DIR)
    return BgeReranker(MODELS_DIR)


def test_a_polish_question_finds_the_english_answer(reranker: BgeReranker) -> None:
    scores = reranker.score(
        "Jak długo dostawcy przechowują rejestry zdarzeń?",
        [
            "Providers keep the logs automatically generated by their high-risk AI systems "
            "for a period of at least six months.",
            "Member States shall designate notifying authorities.",
        ],
    )

    assert scores[0] > scores[1]


def test_the_article_itself_outranks_a_passage_that_cites_it(reranker: BgeReranker) -> None:
    scores = reranker.score(
        "What does Article 83 of the GDPR set out?",
        [
            "Article 84 > Penalties\n\nMember States shall lay down the rules on other "
            "penalties for infringements of this Regulation, in particular for infringements "
            "which are not subject to administrative fines pursuant to Article 83.",
            "Article 83 > General conditions for imposing administrative fines\n\nEach "
            "supervisory authority shall ensure that the imposition of administrative fines "
            "pursuant to this Article shall in each individual case be effective, "
            "proportionate and dissuasive.",
        ],
    )

    assert scores[1] > scores[0]
