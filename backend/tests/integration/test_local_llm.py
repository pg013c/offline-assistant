"""The configured local model answers for real; needs `make llm`, skipped otherwise."""

import asyncio
import os

import httpx
import pytest

from assistant.adapters.openai_compatible_chat import LlmServer, OpenAICompatibleChat
from assistant.domain.answers import Answered, ModelEvent
from assistant.domain.documents import Chunk

pytestmark = pytest.mark.integration

URL = os.environ.get("ASSISTANT_LLM_URL", "http://127.0.0.1:8080")


def server_is_up() -> bool:
    try:
        return httpx.get(f"{URL}/health", timeout=2).status_code == 200
    except httpx.HTTPError:
        return False


PASSAGES = [
    Chunk(
        id="ai:1",
        document_id="ai",
        position=1,
        text="Providers keep the logs automatically generated by their high-risk AI systems "
        "for a period of at least six months.",
    ),
    Chunk(id="ai:2", document_id="ai", position=2, text="Member States designate authorities."),
]


@pytest.mark.skipif(not server_is_up(), reason="no local model server (make llm)")
@pytest.mark.parametrize(
    "question",
    ["How long do providers keep the logs?", "Jak długo dostawcy przechowują rejestry zdarzeń?"],
)
def test_the_local_model_answers_from_the_passages_with_valid_citations(question: str) -> None:
    chat = OpenAICompatibleChat(
        model_id="qwen3-8b",
        server=LlmServer(
            base_url=URL,
            served_model="qwen3-8b",
            timeout_seconds=60,
            max_retries=2,
        ),
    )

    async def gather() -> list[ModelEvent]:
        return [event async for event in chat.answer(question, PASSAGES)]

    outcome = asyncio.run(gather())[-1]

    assert isinstance(outcome, Answered)
    assert 1 in outcome.answer.cited
    assert outcome.usage.first_token_ms is not None
